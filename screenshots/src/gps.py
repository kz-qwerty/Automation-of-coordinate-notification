import math
import time
from collections import deque

from route import get_current_address, move_to_next_address


# ============================================================
# 1. Настройки геозоны
# ============================================================
# Вместо двух разных радиусов (80 м / 55 м) используем
# ОДИН радиус и проверяем не одну пару точек подряд,
# а последние несколько измерений сразу — это устойчивее
# к "прыжкам" GPS (особенно в машине, где сигнал слабее
# и может колебаться на 50-100+ метров между соседними
# обновлениями Live Location, даже если машина стоит
# на месте).

RADIUS_METERS = 80

# Сколько последних измерений храним и анализируем.
WINDOW_SIZE = 4

# Сколько измерений из окна должны попасть в радиус,
# чтобы адрес считался подтверждённым.
MIN_HITS = 2


# ============================================================
# 2. Окно последних измерений координат по каждому водителю
# ============================================================
# Координаты приходят от реального Live Location по одной
# точке за раз (каждое обновление от Telegram — это одно
# новое сообщение edited_message с location).
#
# Раньше хранили только ОДНО предыдущее измерение.
# Теперь храним последние WINDOW_SIZE измерений — это
# позволяет засчитывать адрес, даже если один из замеров
# "прыгнул" из-за помех GPS, пока остальные подтверждают,
# что водитель реально находится рядом с адресом.
#
# driver_location_window — словарь:
#
# {
#     user_id: deque([(latitude, longitude), ...], maxlen=WINDOW_SIZE),
#     ...
# }

driver_location_window: dict[int, deque] = {}


# ============================================================
# 2.1 Время последнего полученного измерения по водителю
# ============================================================
# Используется для проверки таймаута — если во время
# активного маршрута координаты не приходят слишком долго,
# это признак того, что водитель мог отключить трансляцию
# геопозиции (Telegram не присылает боту прямого события
# об этом, поэтому обнаруживаем это только по паузе
# в обновлениях).
#
# driver_last_update_time — словарь:
#
# {
#     user_id: unix_timestamp (float),
#     ...
# }

driver_last_update_time: dict[int, float] = {}


# ============================================================
# 3. Сброс сохранённого измерения водителя
# ============================================================
# Вызывается при старте и при остановке маршрута,
# а также сразу после подтверждения адреса,
# чтобы старые координаты не использовались
# в проверке следующего адреса или следующего маршрута.
#
# Также обновляем время последнего измерения на "сейчас" —
# это даёт водителю время (тайм-аут) на то, чтобы включить
# трансляцию геопозиции после старта маршрута, прежде чем
# бот начнёт считать это подозрительным отсутствием сигнала.

def reset_tracking(user_id: int):

    driver_location_window[user_id] = deque(maxlen=WINDOW_SIZE)
    driver_last_update_time[user_id] = time.time()


# ============================================================
# 3.1 Сколько секунд прошло с последнего измерения
# ============================================================
# Возвращает None, если по этому водителю ещё вообще
# не было ни одного измерения (и не было reset_tracking).

def seconds_since_last_update(user_id: int):

    last_time = driver_last_update_time.get(user_id)

    if last_time is None:
        return None

    return time.time() - last_time


# ============================================================
# 4. Расчёт расстояния между двумя GPS-точками
# ============================================================
# Функция получает координаты двух точек:
#
# Первая точка  — водитель.
# Вторая точка  — адрес.
#
# Возвращает расстояние между ними в метрах.
#
# Используем формулу Haversine.

def calculate_distance(
    latitude_1,
    longitude_1,
    latitude_2,
    longitude_2,
):

    # Средний радиус Земли в метрах.
    earth_radius = 6_371_000

    # Переводим широту из градусов в радианы.
    latitude_1 = math.radians(latitude_1)
    latitude_2 = math.radians(latitude_2)

    # Переводим долготу из градусов в радианы.
    longitude_1 = math.radians(longitude_1)
    longitude_2 = math.radians(longitude_2)

    # Вычисляем разницу координат.
    delta_latitude = latitude_2 - latitude_1
    delta_longitude = longitude_2 - longitude_1

    # Основная часть формулы Haversine.
    a = (
        math.sin(delta_latitude / 2) ** 2
        + math.cos(latitude_1)
        * math.cos(latitude_2)
        * math.sin(delta_longitude / 2) ** 2
    )

    # Получаем центральный угол между точками.
    c = 2 * math.atan2(
        math.sqrt(a),
        math.sqrt(1 - a),
    )

    # Переводим угол в расстояние в метрах.
    distance = earth_radius * c

    return distance


# ============================================================
# 5. Проверка достижения адреса по окну измерений
# ============================================================
# Считаем расстояние от КАЖДОЙ точки в окне (последние
# WINDOW_SIZE измерений) до адреса, и смотрим, сколько
# из них попали в радиус RADIUS_METERS.
#
# Если попаданий >= MIN_HITS — адрес считается
# подтверждённым, даже если часть измерений в окне
# "промахнулась" из-за шума GPS.
#
# Возвращает True / False.

def check_address_reached(
    location_window,
    address_latitude,
    address_longitude,
):

    hits = 0

    # --------------------------------------------------------
    # Проверяем каждую точку окна по очереди.
    # --------------------------------------------------------

    for latitude, longitude in location_window:

        distance = calculate_distance(
            latitude,
            longitude,
            address_latitude,
            address_longitude,
        )

        is_hit = distance <= RADIUS_METERS

        print(
            f"Измерение: {distance:.2f} м "
            f"({'✅ в радиусе' if is_hit else '❌ мимо радиуса'} "
            f"{RADIUS_METERS} м)"
        )

        if is_hit:
            hits += 1

    # --------------------------------------------------------
    # Итог по окну.
    # --------------------------------------------------------

    print(
        f"Попаданий в радиус: {hits} из {len(location_window)} "
        f"(нужно минимум {MIN_HITS})"
    )

    if hits >= MIN_HITS:
        print("🎯 Адрес достигнут!")
        return True

    print("❌ Адрес пока не подтверждён.")
    return False


# ============================================================
# 6. Обработка живого измерения GPS от водителя
# ============================================================
# Эта функция вызывается КАЖДЫЙ РАЗ, когда приходит новое
# обновление Live Location от Telegram (первое сообщение
# или очередной edited_message).
#
# Возвращает один из вариантов:
#
# None       — маршрут не запущен, координату игнорируем.
# "waiting"  — измерений в окне пока меньше MIN_HITS,
#              рано делать вывод, ждём ещё обновления.
# False      — измерений достаточно для проверки, но адрес
#              ещё не достигнут (едем дальше).
# dict       — адрес достигнут, это СЛЕДУЮЩИЙ адрес маршрута.
# "finished" — адрес достигнут, и это был последний адрес,
#              маршрут завершён.

def process_driver_location(
    user_id: int,
    latitude: float,
    longitude: float,
):

    # Получаем текущий адрес маршрута этого водителя.
    current_address = get_current_address(user_id)

    # Если маршрут не запущен — ничего не делаем.
    if current_address is None:
        return None

    # Фиксируем время этого измерения — используется
    # фоновой проверкой таймаута в bot.py.
    driver_last_update_time[user_id] = time.time()

    # Получаем (или создаём) окно измерений этого водителя.
    if user_id not in driver_location_window:
        driver_location_window[user_id] = deque(maxlen=WINDOW_SIZE)

    location_window = driver_location_window[user_id]

    # Добавляем новое измерение в окно.
    # Если окно уже заполнено (WINDOW_SIZE), самое старое
    # измерение автоматически "выпадает" — deque сам
    # следит за этим благодаря maxlen.
    location_window.append((latitude, longitude))

    print(
        f"\nТекущий адрес: {current_address['name']}"
    )

    # ------------------------------------------------------
    # Если в окне ещё меньше измерений, чем нужно для
    # решения (MIN_HITS) — рано делать вывод, ждём ещё.
    # ------------------------------------------------------

    if len(location_window) < MIN_HITS:

        print(
            f"📡 Измерение сохранено ({len(location_window)} "
            f"из {WINDOW_SIZE}), ждём следующее..."
        )

        return "waiting"

    # ------------------------------------------------------
    # Измерений достаточно — проверяем окно целиком.
    # ------------------------------------------------------

    address_reached = check_address_reached(
        location_window,
        current_address["latitude"],
        current_address["longitude"],
    )

    # --------------------------------------------------------
    # Если адрес достигнут — переходим дальше
    # --------------------------------------------------------

    if address_reached:

        # Сбрасываем окно измерений — для следующего адреса
        # (или следующего маршрута) считаем заново с нуля.
        reset_tracking(user_id)

        # Переходим к следующему адресу.
        next_address = move_to_next_address(user_id)

        # Если следующий адрес существует,
        # возвращаем его в bot.py.
        if next_address:

            print(
                f"\n➡️ Следующий адрес: "
                f"{next_address['name']}"
            )

            return next_address

        # Если следующего адреса нет,
        # маршрут завершён.
        print(
            "\n🏁 Все адреса маршрута пройдены."
        )

        return "finished"

    # Если адрес не достигнут,
    # остаёмся на текущем адресе и ждём новых обновлений GPS.
    return False