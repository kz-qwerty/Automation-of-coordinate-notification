# ============================================================
# 1.1 Владельцы адресов (кто имеет право отменить адрес)
# ============================================================
# Каждому адресу может быть жёстко привязан ОДИН Telegram
# user_id — только этот человек может отменить именно этот
# адрес командой /отменить.
#
# Если владелец не указан (None) — адрес вообще нельзя
# отменить командой (например, склад, а не частный клиент).

ADDRESS_OWNERS: dict[str, int | None] = {
    "Адрес 1": None,
    "Адрес 2": None,
    "Адрес 3": None ,
    "Адрес 4": None,
    "Адрес 5": None,
    "Адрес 6": None,
    "Адрес 7": None,
}


def get_address_owner(address_name: str):
    """
    Возвращает user_id владельца адреса, или None,
    если владелец не назначен (адрес нельзя отменить).
    """
    return ADDRESS_OWNERS.get(address_name)


# ============================================================
# 1.2 Отменённые адреса (по датам)
# ============================================================
# Структура:
#
# {
#     "31.08.2026": {
#         "Адрес 2": user_id_кто_отменил,
#         ...
#     },
#     ...
# }
#
# Ключ верхнего уровня — дата в формате ДД.ММ.ГГГГ.
# Так отмена автоматически "работает" только в свой день —
# никакого ручного сброса на следующий день не требуется.

cancelled_addresses: dict[str, dict[str, int]] = {}


def _date_key(target_date: date) -> str:
    return target_date.strftime("%d.%m.%Y")


def is_cancelled_on(address_name: str, target_date: date) -> bool:
    """
    Проверяет, отменён ли этот адрес именно на эту дату.
    """
    key = _date_key(target_date)
    return address_name in cancelled_addresses.get(key, {})


def cancel_address(address_name: str, target_date: date, user_id: int):
    """
    Отмечает адрес как отменённый на указанную дату.
    """
    key = _date_key(target_date)
    cancelled_addresses.setdefault(key, {})[address_name] = user_id


# ============================================================
# 2. Состояние маршрутов всех водителей
# ============================================================
# Состояние храним отдельно для каждого user_id,
# чтобы несколько водителей могли вести маршруты
# одновременно, не мешая друг другу.
#
# route_states — словарь:
#
# {
#     user_id: {
#         "active": bool,
#         "current_address_index": int,
#     },
#     ...
# }

route_states: dict[int, dict] = {}


# ============================================================
# 3. Получение (или создание) состояния маршрута водителя
# ============================================================
# Если для этого водителя ещё нет записи — создаём её
# с начальными значениями.

def get_state(user_id: int) -> dict:

    if user_id not in route_states:

        route_states[user_id] = {
            "active": False,
            "current_address_index": 0,
        }

    return route_states[user_id]


# ============================================================
# 4. Запуск маршрута
# ============================================================
# При запуске устанавливаем:
#
# active = True
# текущий адрес = Адрес 1
#
# Возвращаем первый адрес маршрута.

def start_route(user_id: int, today: date | None = None):

    state = get_state(user_id)

    state["active"] = True
    state["current_address_index"] = 0

    # get_current_address сама пропустит вперёд любые
    # адреса, отменённые именно на сегодняшнюю дату —
    # так что если, например, Адрес 1 отменён с утра,
    # водитель сразу увидит Адрес 2 как первый в маршруте.
    return get_current_address(user_id, today)


# ============================================================
# 5. Получение текущего адреса
# ============================================================
# Эта функция возвращает адрес, к которому сейчас должен
# двигаться водитель.
#
# ВАЖНО: функция САМА пропускает вперёд все адреса,
# отменённые именно на сегодняшнюю дату (если такие есть
# прямо в начале очереди) — водитель никогда не увидит
# отменённый адрес, независимо от того, отменили его
# заранее (утром, до старта) или прямо во время движения.

def get_current_address(user_id: int, today: date | None = None):

    if today is None:
        today = date.today()

    state = get_state(user_id)

    # Если маршрут не запущен,
    # текущего адреса нет.
    if not state["active"]:
        return None

    index = state["current_address_index"]

    # Пропускаем вперёд все подряд отменённые на сегодня
    # адреса, начиная с текущего индекса.
    while index < len(ROUTE_ADDRESSES):

        address = ROUTE_ADDRESSES[index]

        if is_cancelled_on(address["name"], today):
            index += 1
            continue

        # Нашли первый не отменённый адрес — фиксируем индекс
        # и возвращаем его.
        state["current_address_index"] = index
        return address

    # Все оставшиеся адреса до конца списка отменены —
    # маршрут для этого водителя считается завершённым.
    state["active"] = False
    return None


# ============================================================
# 6. Переход к следующему адресу
# ============================================================
# Эта функция используется после того,
# как GPS определит прибытие водителя в текущий адрес.
#
# Например:
#
# Адрес 1 достигнут
#       ↓
# move_to_next_address(user_id)
#       ↓
# Текущий адрес = Адрес 2

def move_to_next_address(user_id: int, today: date | None = None):

    state = get_state(user_id)

    # Просто сдвигаем индекс на один шаг вперёд.
    # Если в списке дальше не осталось адресов вообще —
    # get_current_address сама обнаружит это и корректно
    # завершит маршрут (state["active"] = False).
    state["current_address_index"] += 1

    # get_current_address сама пропустит вперёд любые
    # отменённые на сегодня адреса, если они окажутся
    # следующими в очереди.
    return get_current_address(user_id, today)


# ============================================================
# 6.1 Мгновенный пропуск ТЕКУЩЕГО адреса, если его отменили
# ============================================================
# Вызывается из bot.py сразу после успешной команды
# /отменить — ПРОВЕРЯЕТ, является ли только что отменённый
# адрес именно тем, к которому водитель сейчас едет.
#
# Если да — сдвигает маршрут вперёд НЕМЕДЛЕННО, не дожидаясь
# следующего обновления GPS.
#
# Возвращает:
#
# None                     — пропускать нечего (либо маршрут
#                             не активен у этого водителя,
#                             либо его текущий адрес — не тот,
#                             что только что отменили).
# (old_name, new_address)  — адрес был пропущен; new_address
#                             это следующий адрес (dict)
#                             или None, если адресов больше
#                             не осталось (маршрут завершён).

def skip_if_current_cancelled(user_id: int, today: date | None = None):

    if today is None:
        today = date.today()

    state = get_state(user_id)

    if not state["active"]:
        return None

    index = state["current_address_index"]

    if index >= len(ROUTE_ADDRESSES):
        return None

    current = ROUTE_ADDRESSES[index]

    # Текущий адрес не отменён — пропускать не требуется.
    if not is_cancelled_on(current["name"], today):
        return None

    # Текущий адрес отменён — сдвигаем индекс вперёд.
    # get_current_address сама пропустит и все следующие
    # подряд отменённые адреса, если такие есть.
    state["current_address_index"] = index + 1
    new_current = get_current_address(user_id, today)

    return (current["name"], new_current)


# ============================================================
# 7. Завершение маршрута вручную
# ============================================================
# Эта функция вызывается кнопкой
# «⛔️ Завершить маршрут».

def stop_route(user_id: int):

    state = get_state(user_id)

    # Останавливаем маршрут.
    state["active"] = False

    # Возвращаем состояние в начало,
    # чтобы следующий маршрут снова начинался с Адреса 1.
    state["current_address_index"] = 0


# ============================================================
# 8. Список активных водителей
# ============================================================
# Используется фоновой проверкой таймаута GPS в bot.py —
# чтобы знать, для кого сейчас нужно проверять, не пропали
# ли координаты (не отключил ли водитель трансляцию).

def get_active_user_ids() -> list[int]:

    return [
        user_id
        for user_id, state in route_states.items()
        if state["active"]
    ]